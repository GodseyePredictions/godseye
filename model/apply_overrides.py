"""Apply user reads and late news (overrides.json) on top of the console's weekly snapshot.

The touchdown model cannot be re-run from this repo, so an override does three careful things:
  1. re-estimates the affected players' touchdown chance from expected snap share, and labels it an estimate;
  2. makes those players singles only, so no parlay or hybrid is built on an estimate;
  3. withdraws prop lines and precomputed tickets that were priced on the old role.

Usage: python3 apply_overrides.py     writes ../public/console/personnel-update.js
game_markets.py imports apply() so its own slips and hybrids see the same changes.
"""
import copy
import json
import math
from pathlib import Path

HERE = Path(__file__).parent
CONSOLE = HERE.parent / "public" / "console"


def plan(D: dict) -> dict:
    """Work out the changes without touching D."""
    spec = json.loads((HERE / "overrides.json").read_text())
    by_id = {p["id"]: p for p in D["players"]}
    out = {"players": [], "singles": [], "personnel": [], "stale_ids": [], "drop_props": []}
    for o in spec["overrides"]:
        lead = o["lead_back"]
        template = by_id.get(lead["id"])
        if template is None:
            continue
        rate = -math.log(1 - lead["p"]) / lead["snap_share_when_priced"]   # scoring rate at a full workload
        for pl in o["players"]:
            p_new = round(1 - math.exp(-rate * pl["snap_share"]), 4)
            note = (f"ESTIMATE, not model output. {o['read']} {o['method']} "
                    f"That puts {pl['name']} at about {p_new:.0%}. Singles only until the model is re-run.")
            base = copy.deepcopy(by_id.get(pl["id"], template))
            base.update({"id": pl["id"], "name": pl["name"], "pos": pl["pos"], "p": p_new, "singles": True,
                         "risk": note, "why": [f"<b>Late news:</b> {note}"], "estimate": True,
                         "riskm": {k: note for k in (template.get("riskm") or {})}})
            if pl.get("new"):
                base["intel"] = {**{k: 0 for k in template["intel"]}, "snap": pl["snap_share"],
                                 **{k: template["intel"][k] for k in ("team_rush_td", "team_pass_td", "spread", "implied") if k in template["intel"]}}
                base["parts"] = {**template.get("parts", {}), "role": f"<b>Role:</b> {note}", "form": "<b>Form:</b> not priced by the model this week."}
                base["vol"] = {k: [0.0, 0.0] for k in (template.get("vol") or {})}
                base["missed4"], base["back"] = 1, 0
            out["players"].append(base)
            out["singles"].append({"name": pl["name"], "team": o["team"], "pos": pl["pos"], "p": p_new, "why": pl["singles_reason"]})
            out["stale_ids"].append(pl["id"])
            out["drop_props"].append(pl["id"])
        out["personnel"].append({"type": "override", "name": o["read"], "status": "user read", "team": o["team"],
                                 "note": f"{o['evidence']} Affected numbers are estimates and singles only; tickets and prop lines priced on the old role were withdrawn."})
    return out


def apply(D: dict) -> dict:
    """Return D with the overrides applied (used by game_markets.py)."""
    ch = plan(D)
    ids = {p["id"] for p in ch["players"]}
    D["players"] = sorted([p for p in D["players"] if p["id"] not in ids] + ch["players"], key=lambda p: -p["p"])
    for i in ch["drop_props"]:
        D["props"].pop(i, None)
    D["singles"] = D.get("singles", []) + ch["singles"]
    D["personnel"] = D.get("personnel", []) + ch["personnel"]
    return D


JS = r"""/* Generated by model/apply_overrides.py from model/overrides.json. Applies user reads and late news. */
(function(){var U=__PAYLOAD__;
U.players.forEach(function(p){var i=D.players.findIndex(function(x){return x.id===p.id});if(i<0)D.players.push(p);else D.players[i]=p});
D.players.sort(function(a,b){return b.p-a.p});
U.drop_props.forEach(function(id){delete D.props[id]});
var stale=new Set(U.stale_ids);
var has=function(t){return !!t&&Array.isArray(t.legs)&&t.legs.some(function(l){return stale.has(typeof l==="string"?l:l.id)})};
var clean=function(a){return Array.isArray(a)?a.filter(function(t){return !has(t)}):a};
var A=D.algo||{};["atd","atd_combos","props","sgp"].forEach(function(k){A[k]=clean(A[k])});
Object.keys(A.atd_styles||{}).forEach(function(k){A.atd_styles[k].tickets=clean(A.atd_styles[k].tickets)});
Object.keys(D.crossgame||{}).forEach(function(k){D.crossgame[k]=clean(D.crossgame[k])});
(D.script_sgp||[]).forEach(function(t){t.ladder=clean(t.ladder||[]);["hybrid","hybrid1","hybrid2"].forEach(function(k){if(has(t[k]))t[k]=null})});
D.singles=(D.singles||[]).concat(U.singles);
D.personnel=(D.personnel||[]).concat(U.personnel);
D.meta.overrides=(D.meta.overrides||0)+U.personnel.length;})();
"""


def main():
    D = json.loads((CONSOLE / "data.js").read_text(encoding="utf8").strip()[len("const D = "):].rstrip(";"))
    ch = plan(D)
    (CONSOLE / "personnel-update.js").write_text(JS.replace("__PAYLOAD__", json.dumps(ch)), encoding="utf8")
    for p in ch["players"]:
        print(p["name"], p["p"], "singles only")
    print(len(ch["personnel"]), "override(s) written")


if __name__ == "__main__":
    main()
