"""Fetch current game lines for the coming NFL week.

Source: ESPN's public scoreboard, which carries DraftKings lines (moneyline, spread and total
with prices). It is not bet365: bet365 publishes no feed. Lines at the two books are usually
within a few cents on game markets, and can differ more on props.

Usage: python3 fetch_odds.py
Writes data/live_odds.json and ../public/console/odds-update.js (which refreshes the lines the
console shows).
"""
import json
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).parent
URL = "https://site.api.espn.com/apis/site/v2/sports/football/nfl/scoreboard"
TEAM = {"WSH": "WAS", "LAR": "LA"}   # ESPN abbreviations that differ from the model's


def num(x):
    if x is None:
        return None
    s = str(x).replace("o", "").replace("u", "").replace("+", "").strip()
    if s.upper() in ("EVEN", "EV"):
        return 100.0
    try:
        return float(s)
    except ValueError:
        return None


def main():
    req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0"})
    data = json.load(urllib.request.urlopen(req, timeout=60))
    games = {}
    for e in data["events"]:
        c = e["competitions"][0]
        if not c.get("odds"):
            continue
        o = c["odds"][0]
        home = next(t for t in c["competitors"] if t["homeAway"] == "home")["team"]["abbreviation"]
        away = next(t for t in c["competitors"] if t["homeAway"] == "away")["team"]["abbreviation"]
        home, away = TEAM.get(home, home), TEAM.get(away, away)
        cur = lambda node: (node or {}).get("close") or (node or {}).get("open") or {}
        ml, ps, tot = o.get("moneyline", {}), o.get("pointSpread", {}), o.get("total", {})
        row = {
            "home": home, "away": away, "kickoff": e["date"], "provider": o.get("provider", {}).get("name"),
            "home_spread": num(cur(ps.get("home")).get("line")), "home_spread_odds": num(cur(ps.get("home")).get("odds")),
            "away_spread_odds": num(cur(ps.get("away")).get("odds")),
            "total": num(cur(tot.get("over")).get("line")), "over_odds": num(cur(tot.get("over")).get("odds")),
            "under_odds": num(cur(tot.get("under")).get("odds")),
            "home_ml": num(cur(ml.get("home")).get("odds")), "away_ml": num(cur(ml.get("away")).get("odds")),
        }
        if row["home_spread"] is None and o.get("spread") is not None:
            row["home_spread"] = float(o["spread"])
        if row["total"] is None and o.get("overUnder") is not None:
            row["total"] = float(o["overUnder"])
        games[f"{away}@{home}"] = row
    out = {"fetched_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
           "source": "DraftKings lines via ESPN", "week": data.get("week", {}).get("number"), "games": games}
    (HERE / "data").mkdir(exist_ok=True)
    json.dump(out, open(HERE / "data/live_odds.json", "w"), indent=1)

    # The console keeps its own copy of each game's line; this refreshes it when the page loads.
    lines = {k: {"spread_home": -g["home_spread"], "total": g["total"]} for k, g in games.items()
             if g["home_spread"] is not None and g["total"] is not None}
    js = ("/* Generated by model/fetch_odds.py. Refreshes the game lines the console displays. */\n"
          f"(function(){{var L={json.dumps(lines)};var at={json.dumps(out['fetched_at'])};\n"
          "D.games.forEach(function(g){var l=L[g.away+'@'+g.home];if(!l)return;g.spread_home=l.spread_home;g.total=l.total;\n"
          "g.implied={};g.implied[g.home]=Math.round((l.total+l.spread_home)*5)/10;g.implied[g.away]=Math.round((l.total-l.spread_home)*5)/10;});\n"
          "D.meta.odds_asof=at;})();\n")
    (HERE.parent / "public/console/odds-update.js").write_text(js)
    print(out["fetched_at"], out["source"], len(games), "games")
    for k, g in list(games.items())[:4]:
        print(k, g["home_spread"], g["home_spread_odds"], g["total"], g["over_odds"], g["home_ml"], g["away_ml"])


if __name__ == "__main__":
    main()
